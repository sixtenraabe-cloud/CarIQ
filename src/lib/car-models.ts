export function normalizeBrand(input: string): string | null {
  const q = input.trim().toLowerCase();
  if (!q) return null;
  return Object.keys(CAR_MODELS).find((b) => b.toLowerCase() === q) ?? null;
}

export function modelsFor(brandInput: string): string[] {
  const brand = normalizeBrand(brandInput);
  return brand ? CAR_MODELS[brand]! : [];
}

export function suggestModels(brandInput: string, query: string, limit = 8): string[] {
  const list = modelsFor(brandInput);
  const q = query.trim().toLowerCase();
  if (!q) return list.slice(0, limit);
  const starts = list.filter((m) => m.toLowerCase().startsWith(q));
  const contains = list.filter((m) => !m.toLowerCase().startsWith(q) && m.toLowerCase().includes(q));
  return [...starts, ...contains].slice(0, limit);
}

export function isKnownCar(brandInput: string, modelInput: string): boolean {
  const list = modelsFor(brandInput);
  if (!list.length) return false;
  const m = modelInput.trim().toLowerCase();
  return list.some((x) => x.toLowerCase() === m);
}
