const DICTS: Record<Lang, Dict> = { sv, en, da, de };

const KEY = "cariq.lang";

type Ctx = { lang: Lang; setLang: (lang: Lang) => void; t: Dict };
const LanguageContext = createContext<Ctx>({ lang: "sv", setLang: () => {}, t: sv });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("sv");

  useEffect(() => {
    const stored = window.localStorage.getItem(KEY) as Lang | null;
    if (stored && stored in DICTS) setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      t: DICTS[lang],
      setLang: (next: Lang) => {
        setLangState(next);
        window.localStorage.setItem(KEY, next);
      },
    }),
    [lang],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}

export function currencyFor(lang: Lang) {
  return LANGUAGES.find((l) => l.code === lang)!;
}
